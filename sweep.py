"""
Sweep harness for SwarmSim.

Configurations are grouped by their compile-time signature so each binary is
built once and reused for every runtime variant. Results append to a JSONL
file, so an interrupted sweep resumes without losing work.

  ./sweep.py                     run every sweep
  ./sweep.py lattice_cell        run one sweep
  ./sweep.py --list              show available sweeps
"""

import glob
import hashlib
import itertools
import json
import os
import platform
import shutil
import subprocess
import sys
import time
from pathlib import Path

ROOT       = Path(__file__).resolve().parent
BUILD_DIR  = ROOT / "sweep_build"
BIN_CACHE  = ROOT / "sweep_bins"
SWEEP_HDR  = ROOT / "include" / "Core" / "SweepConfig.h"
RESULTS    = ROOT / "sweep_results.jsonl"

RUN_TIMEOUT = 1800      # seconds per configuration
COOLDOWN    = 5         # seconds between runs, to limit thermal drift

# Parameters requiring a rebuild. Names match the SWEEP_* macros in Config.h.
COMPILE_PARAMS = [
    "NUM_CELLE_X", "NUM_CELLE_Y",
    "LATTICE_CELL_WIDTH", "LATTICE_CELL_HEIGHT",
    "FOOD_CELL_WIDTH", "FOOD_CELL_HEIGHT",
    "MAX_AGENTS_PER_CELL", "HIDDEN_LAYER_SIZE",
    "MAX_SWARM_CAPACITY", "FOOD_CHUNK_REFRESH_INTERVAL",
]

# Runtime parameters -> CLI flag.
RUNTIME_FLAGS = {
    "prey":         "--prey",
    "predators":    "--predators",
    "worlds":       "--worlds",
    "grid_mult":    "--grid-mult",
    "grass_radius": "--grass-radius",
    "pred_radius":  "--pred-radius",
    "gen_duration": "--gen-duration",
    "seed":         "--seed",
    "generations":  "--generations",
}


# ------------------------------------------------------------------ build

def compile_signature(cfg):
    items = [(k, cfg[k]) for k in COMPILE_PARAMS if k in cfg]
    return hashlib.sha1(repr(sorted(items)).encode()).hexdigest()[:12]


def write_sweep_header(cfg):
    lines = ["#pragma once", "// Generated by sweep.py - do not edit", ""]
    for k in COMPILE_PARAMS:
        if k in cfg:
            lines.append(f"#define SWEEP_{k} {cfg[k]}")
    SWEEP_HDR.parent.mkdir(parents=True, exist_ok=True)
    SWEEP_HDR.write_text("\n".join(lines) + "\n")


def build(cfg):
    sig = compile_signature(cfg)
    cached = BIN_CACHE / f"SwarmSim_{sig}"
    if cached.exists():
        return cached

    print(f"    building {sig} ...", end="", flush=True)
    write_sweep_header(cfg)
    BIN_CACHE.mkdir(exist_ok=True)

    t0 = time.time()
    subprocess.run(
        ["cmake", "-S", str(ROOT), "-B", str(BUILD_DIR),
         "-DBUILD_GUI=OFF", "-DCMAKE_BUILD_TYPE=Release"],
        check=True, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE)
    subprocess.run(
        ["cmake", "--build", str(BUILD_DIR), "-j", str(os.cpu_count() or 4)],
        check=True, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE)

    print(f" {time.time() - t0:.0f}s", flush=True)

    shutil.copy2(BUILD_DIR / "SwarmSim", cached)
    cached.chmod(0o755)
    return cached


# --------------------------------------------------------------- platform

def _first_line(path):
    try:
        return Path(path).read_text().strip().split("\n")[0]
    except Exception:
        return None


def platform_state():
    """Clocks and temperatures. All readable without sudo on JetPack."""
    s = {"host": platform.node(), "machine": platform.machine()}

    for pat in ("/sys/class/devfreq/*/cur_freq",
                "/sys/devices/platform/gpu.0/devfreq/*/cur_freq",
                "/sys/devices/gpu.0/devfreq/*/cur_freq"):
        hit = False
        for p in sorted(glob.glob(pat)):
            v = _first_line(p)
            if v and v.isdigit():
                s["gpu_freq_hz"] = int(v)
                hit = True
                break
        if hit:
            break

    cpu = _first_line("/sys/devices/system/cpu/cpu0/cpufreq/scaling_cur_freq")
    if cpu and cpu.isdigit():
        s["cpu0_khz"] = int(cpu)

    temps = []
    for p in sorted(glob.glob("/sys/devices/virtual/thermal/thermal_zone*/temp")):
        v = _first_line(p)
        if v and v.lstrip("-").isdigit():
            temps.append(int(v) / 1000.0)
    if temps:
        s["temp_max_c"] = max(temps)

    mode = _first_line("/var/lib/nvpmodel/status")
    if mode:
        s["nvpmodel"] = mode

    return s


# -------------------------------------------------------------------- run

def run_one(binary, cfg):
    cmd = [str(binary), "--json"]
    for key, flag in RUNTIME_FLAGS.items():
        if key in cfg:
            cmd += [flag, str(cfg[key])]
    cmd += ["--tag", cfg.get("sweep", "")]

    before = platform_state()
    t0 = time.time()

    try:
        proc = subprocess.run(cmd, capture_output=True, text=True,
                              timeout=RUN_TIMEOUT, cwd=str(ROOT))
    except subprocess.TimeoutExpired:
        print("    TIMEOUT", flush=True)
        return []

    after = platform_state()

    if proc.returncode != 0:
        print(f"    FAILED rc={proc.returncode}: {proc.stderr.strip()[:300]}", flush=True)
        return []

    header, rows = {}, []
    for line in proc.stdout.splitlines():
        line = line.strip()
        if not line.startswith("{"):
            continue
        try:
            obj = json.loads(line)
        except json.JSONDecodeError:
            continue
        if obj.get("type") == "header":
            header = obj
        elif obj.get("type") == "gen":
            rows.append(obj)

    out = []
    for r in rows:
        r["config"] = cfg
        r["header"] = header
        r["platform_before"] = before
        r["platform_after"] = after
        r["wall_s"] = time.time() - t0
        out.append(r)
    return out


# ----------------------------------------------------------------- sweeps

BASE = {
    # compile-time
    "NUM_CELLE_X": 960, "NUM_CELLE_Y": 540,
    "LATTICE_CELL_WIDTH": 30, "LATTICE_CELL_HEIGHT": 30,
    "FOOD_CELL_WIDTH": 10, "FOOD_CELL_HEIGHT": 10,
    "MAX_AGENTS_PER_CELL": 64, "HIDDEN_LAYER_SIZE": 8,
    "MAX_SWARM_CAPACITY": 40000, "FOOD_CHUNK_REFRESH_INTERVAL": 20,
    # runtime
    "prey": 400, "predators": 50, "worlds": 1,
    "grid_mult": 8, "generations": 4, "gen_duration": 10.0,
}


def expand(base, **axes):
    keys = list(axes)
    out = []
    for combo in itertools.product(*(axes[k] for k in keys)):
        cfg = dict(base)
        cfg.update(dict(zip(keys, combo)))
        out.append(cfg)
    return out


def square(cell):
    """Lattice cells are square; keep width and height in step."""
    return {"LATTICE_CELL_WIDTH": cell, "LATTICE_CELL_HEIGHT": cell}


SWEEPS = {
    # Highest value: tests the O(N^2) lattice scaling head-on.
    "lattice_cell": [
        {**BASE, **square(c), "prey": 4000, "predators": 200}
        for c in (10, 15, 20, 30, 45, 60)
    ],

    # Decides whether world batching is worth implementing.
    "world_count": expand(BASE, worlds=[1, 2, 4, 8, 11]),

    "population": expand(
        {**BASE, "predators": 50},
        prey=[512, 1024, 2048, 4096, 8192, 16384]),

    # Constant agent density, growing area: isolates memory footprint effects.
    "const_density": [
        {**BASE, "NUM_CELLE_X": x, "NUM_CELLE_Y": y,
         "prey": p, "predators": max(1, p // 20),
         "MAX_SWARM_CAPACITY": max(40000, p * 4)}
        for x, y, p in [(480, 270, 1000), (960, 540, 4000),
                        (1920, 1080, 16000), (3840, 2160, 64000)]
    ],

    # Constant agent count, growing area: isolates density.
    "const_count": [
        {**BASE, "NUM_CELLE_X": x, "NUM_CELLE_Y": y,
         "prey": 4000, "predators": 200}
        for x, y in [(480, 270), (960, 540), (1920, 1080), (3840, 2160)]
    ],

    "sensing_radius": expand(
        {**BASE, "prey": 4000, "predators": 200},
        grass_radius=[20, 35, 50, 75, 100]),

    "food_refresh": expand(
        {**BASE, "prey": 4000, "predators": 200},
        FOOD_CHUNK_REFRESH_INTERVAL=[1, 5, 10, 20, 50]),

    "grid_mult": expand(
        {**BASE, "prey": 4000, "predators": 200},
        grid_mult=[1, 2, 4, 8, 16]),

    "brain_size": expand(
        {**BASE, "prey": 4000, "predators": 200},
        HIDDEN_LAYER_SIZE=[4, 8, 16, 32]),
}

SEEDS = [11111, 22222, 33333]


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    if "--list" in sys.argv:
        for name, cfgs in SWEEPS.items():
            print(f"  {name:16s} {len(cfgs)} configs")
        return 0

    wanted = args or list(SWEEPS)
    for name in wanted:
        if name not in SWEEPS:
            print(f"unknown sweep '{name}'; try --list")
            return 1

    configs = []
    for name in wanted:
        for cfg in SWEEPS[name]:
            for seed in SEEDS:
                configs.append({**cfg, "seed": seed, "sweep": name})

    # Group by compile signature so each binary is built once.
    configs.sort(key=compile_signature)

    done = set()
    if RESULTS.exists():
        for line in RESULTS.read_text().splitlines():
            try:
                done.add(repr(sorted(json.loads(line)["config"].items())))
            except Exception:
                pass

    n_builds = len(set(map(compile_signature, configs)))
    print(f"{len(configs)} configurations, {n_builds} builds required")

    with RESULTS.open("a") as out:
        for i, cfg in enumerate(configs, 1):
            key = repr(sorted(cfg.items()))
            if key in done:
                print(f"[{i}/{len(configs)}] cached")
                continue

            varied = {k: v for k, v in cfg.items()
                      if k not in BASE or BASE.get(k) != v}
            print(f"[{i}/{len(configs)}] {cfg['sweep']} {varied}", flush=True)

            try:
                binary = build(cfg)
            except subprocess.CalledProcessError as e:
                print(f"    BUILD FAILED: {e.stderr.decode()[-500:]}")
                continue

            rows = run_one(binary, cfg)
            for r in rows:
                out.write(json.dumps(r) + "\n")
            out.flush()

            if not rows:
                print("    no rows produced")

            time.sleep(COOLDOWN)

    print(f"done -> {RESULTS}")
    return 0


if __name__ == "__main__":
    sys.exit(main())